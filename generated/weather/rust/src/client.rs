    /// Drives the "local set -> request server update -> await ack" loop for a
    /// single property.  All properties share this one implementation; the
    /// per-property specifics (which payload type to send, how to pull the value
    /// back out of the server's response) are supplied by the `make_payload` and
    /// `extract_value` closures.  This keeps `run_loop` free of one large copy of
    /// this logic per property.
    ///
    /// * `T` is the property's value type (what the application sets).
    /// * `P` is the serializable wire payload for the property.  For single-value
    ///   properties `P` is the generated `*Property` struct; for multi-value
    ///   properties `P` and `T` are the same struct.
    #[allow(clippy::too_many_arguments)]
    async fn run_property_update_request_handler<T, P, MakePayload, ExtractValue>(
        property_name: &'static str,
        mut request_rx: tokio::sync::mpsc::Receiver<(T, Option<oneshot::Sender<Option<T>>>)>,
        mut publisher: C,
        resp_map: Arc<Mutex<HashMap<Uuid, oneshot::Sender<MethodReturnCode>>>>,
        update_topic: String,
        response_topic: String,
        version: Arc<AtomicU32>,
        make_payload: MakePayload,
        extract_value: ExtractValue,
    ) where
        T: std::fmt::Debug + Send + 'static,
        P: serde::Serialize + serde::de::DeserializeOwned + std::fmt::Debug + Send + 'static,
        MakePayload: Fn(T) -> P + Send + 'static,
        ExtractValue: Fn(P) -> T + Send + 'static,
    {
        while let Some((value, opt_responder)) = request_rx.recv().await {
            debug!(
                "Property {} has changed locally to {:?}, sending update request to server",
                property_name, value
            );
            let payload_obj = make_payload(value);
            let correlation_id = Uuid::new_v4();
            let (sender, receiver) = oneshot::channel();
            {
                let mut hashmap = resp_map.lock().expect("Mutex was poisoned");
                hashmap.insert(correlation_id, sender);
            }
            match message::property_update_request(
                &update_topic,
                &payload_obj,
                version.load(Ordering::Relaxed),
                correlation_id,
                response_topic.clone(),
            ) {
                Ok(msg) => {
                    debug!(
                        "Publishing property update request for '{}' to topic '{}': {:?}",
                        property_name, update_topic, payload_obj
                    );
                    let _publish_result = publisher.publish(msg).await;
                    let result = receiver.await;
                    debug!(
                        "Received property update response for '{}': {:?}",
                        property_name, result
                    );
                    match result {
                        Ok(MethodReturnCode::Success(opt_response_text)) => {
                            if let Some(responder) = opt_responder {
                                if let Some(response_text) = opt_response_text {
                                    let resp_obj =
                                        serde_json::from_str::<P>(response_text.as_ref()).unwrap();
                                    let _ = responder.send(Some(extract_value(resp_obj)));
                                } else {
                                    warn!("No response payload received for property update request for '{}'", property_name);
                                    let _ = responder.send(None);
                                }
                            } else {
                                info!(
                                    "No responder provided for property update request for '{}'",
                                    property_name
                                );
                            }
                        }
                        _ => {
                            warn!(
                                "Property update request for '{}' failed: {:?}",
                                property_name, result
                            );
                            if let Some(responder) = opt_responder {
                                let _ = responder.send(None);
                            }
                        }
                    };
                }
                Err(e) => {
                    warn!(
                        "Failed to create property update message for '{}': {:?}",
                        property_name, e
                    );
                    if let Some(responder) = opt_responder {
                        let _ = responder.send(None);
                    }
                }
            }
        }
    }

